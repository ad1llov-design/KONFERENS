export function getLocalizedCourse(course: Course, locale: Locale): Course {
  const loc = COURSE_TRANSLATIONS[locale]?.[course.id];
  if (!loc) return course;

  return {
    ...course,
    title: loc.title || course.title,
    tagline: loc.tagline || course.tagline,
    description: loc.description || course.description,
    level: loc.level || course.level,
    topicsPreview: loc.topicsPreview || course.topicsPreview,
  };
}
