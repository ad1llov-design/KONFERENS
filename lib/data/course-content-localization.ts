// ── Helper functions ────────────────────────────────────────────────────────

export function getLocalizedLesson(courseId: CourseId, lesson: Lesson, locale: Locale): Lesson {
  if (locale === 'en') return lesson;

  const translation = LESSON_TRANSLATIONS[locale]?.[lesson.id];
  if (!translation) return lesson;

  const localizedExercise: Exercise = {
    ...lesson.exercise,
    question: translation.exercise?.question ?? lesson.exercise.question,
    options: translation.exercise?.options ?? lesson.exercise.options,
    explanation: translation.exercise?.explanation ?? lesson.exercise.explanation,
    hint: translation.exercise?.hint ?? lesson.exercise.hint,
  };

  return {
    ...lesson,
    title: translation.title ?? lesson.title,
    content: translation.content ?? lesson.content,
    exercise: localizedExercise,
  };
}

export function getLocalizedStage(courseId: CourseId, stage: Stage, locale: Locale): Stage {
  if (locale === 'en') return stage;

  const stageMeta = STAGE_TRANSLATIONS[locale]?.[stage.id];
  const localizedLessons = stage.lessons.map(l => getLocalizedLesson(courseId, l, locale));

  return {
    ...stage,
    title: stageMeta?.title ?? stage.title,
    description: stageMeta?.description ?? stage.description,
    lessons: localizedLessons,
  };
}

export function getLocalizedCourseWithStages(course: Course, locale: Locale): Course {
  const baseLoc = getLocalizedCourse(course, locale);
  const localizedStages = course.stages.map(s => getLocalizedStage(course.id, s, locale));

  return {
    ...baseLoc,
    stages: localizedStages,
  };
}
